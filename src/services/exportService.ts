import JSZip from 'jszip';
import { EnrichedRecord } from '../types';
import { generateDailyBriefMarkdown } from './dailyBriefService';

export interface ManifestRow {
  source_type: string;
  source_id: string;
  record_ref: string;
  applied_revision: number;
  routes: string[];
  output_paths: string[];
  processing_state: string;
  is_manual_override: boolean;
  analysis_freshness: string;
  evidence_citations_count: number;
  derived_account: string | null;
  person: string;
  person_role: string;
}

export function sanitizeFileName(name: string): string {
  return name.replace(/[^a-zA-Z0-9_\-]/g, '_').toLowerCase();
}

export function generateConversationMarkdown(record: EnrichedRecord, route: string): string {
  const isCall = record.source_type === 'call';
  const a = record.analysis;

  let md = `# SpendNest Revenue Intelligence Output\n`;
  md += `**Record Reference:** ${record.record_ref}  \n`;
  md += `**Source Type:** ${record.source_type}  \n`;
  md += `**Source ID:** \`${record.source_id}\`  \n`;
  md += `**Applied Revision:** v${record.applied_revision}  \n`;
  md += `**Target Route:** ${route}  \n`;
  md += `**Assigned Rep / Organizer:** ${record.personName} (${record.personRole})  \n`;
  md += `**Account / Organization:** ${record.derivedAccount || 'Unspecified'}  \n`;
  md += `**Activity Date (Asia/Kolkata):** ${record.localDate} at ${record.localTime} IST  \n`;
  md += `**Processing State:** ${record.processingState}  \n`;
  md += `**Manual Override Active:** ${record.isManualOverride ? 'YES (Manager Confirmed)' : 'NO (Automated Suggestion)'}  \n`;
  md += `**Analysis Freshness:** ${record.analysisFreshness}  \n\n`;
  md += `---\n\n`;

  if (!a) {
    md += `## Metadata-Only Record Summary\n\n`;
    md += `No usable transcript text was supplied in this assessment delivery batch.  \n`;
    md += `* Intake Status: ${record.processingState}\n`;
    md += `* Upstream Stored Connection Status: ${isCall ? String((record.payload as any).is_connected) : 'N/A'}\n`;
    md += `* Note: As per assessment instructions, no substantive analysis is fabricated for missing/silent records.\n`;
    return md;
  }

  md += `## Executive Summary & What Happened\n\n`;
  md += `### ${a.headline}\n\n`;
  md += `${a.whatHappened}\n\n`;

  md += `## Why It Matters\n\n`;
  md += `${a.whyItMatters}\n\n`;

  md += `## Supporting Evidence & Transcript Citations\n\n`;
  if (a.supportingCitations && a.supportingCitations.length > 0) {
    a.supportingCitations.forEach((cit, idx) => {
      md += `**Passage ${idx + 1} (${cit.citation}):**\n`;
      md += `> "${cit.quote}"\n\n`;
      md += `*Analysis:* ${cit.significance}\n\n`;
    });
  } else {
    md += `*No specific citations recorded.*\n\n`;
  }

  md += `## Honest Uncertainty: What the Evidence Does NOT Establish\n\n`;
  if (a.whatEvidenceDoesNotEstablish && a.whatEvidenceDoesNotEstablish.length > 0) {
    a.whatEvidenceDoesNotEstablish.forEach(item => {
      md += `- [UNVERIFIED] ${item}\n`;
    });
    md += `\n`;
  } else {
    md += `- All factual claims are grounded directly in the supplied transcript.\n\n`;
  }

  md += `## Action Items & Next Steps\n\n`;
  if (a.statedNextSteps && a.statedNextSteps.length > 0) {
    a.statedNextSteps.forEach(ns => {
      md += `- [ ] **${ns.task}**  \n`;
      md += `  *Owner:* **${ns.owner}** ${ns.isExplicitlyStated ? '(Explicitly stated in dialogue)' : '(Manager assigned)'}  \n`;
      if (ns.deadline) {
        md += `  *Target Deadline:* ${ns.deadline}  \n`;
      }
    });
    md += `\n`;
  } else {
    md += `*No immediate action items identified.*\n\n`;
  }

  if (a.coachingNotes) {
    md += `## Manager Coaching Recommendations\n\n`;
    md += `${a.coachingNotes}\n\n`;
  }

  if (a.commercialSignals) {
    md += `## Stated Commercial Signals\n\n`;
    md += `* **Currencies & Figures Mentioned:** ${a.commercialSignals.currenciesMentioned.join(', ') || 'None'}\n`;
    md += `* **Stated Products Under Discussion:** ${a.commercialSignals.statedProducts.join(', ') || 'None'}\n`;
    md += `* **Factual Boundary:** ${a.commercialSignals.caution}\n\n`;
  }

  md += `---\n*Generated by SpendNest Revenue Intelligence Engine - Exported for Review.*`;
  return md;
}

export function buildExportBundle(records: EnrichedRecord[]) {
  const manifestRows: ManifestRow[] = [];
  const files: Record<string, string> = {};

  records.forEach(r => {
    const safeAcc = sanitizeFileName(r.derivedAccount || r.record_ref);
    const outputPaths: string[] = [];

    // Organize files into distinct route folders
    r.assignedRoutes.forEach(route => {
      let folder = 'general';
      switch (route) {
        case 'Sales Coaching':
          folder = 'coaching';
          break;
        case 'Deal Next Steps':
          folder = 'deal_next_steps';
          break;
        case 'Partnerships & Channel':
          folder = 'partnerships';
          break;
        case 'Customer Support / Bugs':
          folder = 'customer_support';
          break;
        case 'Customer Retention':
          folder = 'customer_retention';
          break;
        case 'Vendor Evaluation':
          folder = 'vendor_evaluations';
          break;
        case 'Internal Operations':
          folder = 'internal_ops';
          break;
        case 'Voicemail / Gatekeeper':
          folder = 'voicemail_gatekeeper';
          break;
        case 'Disqualified / Unqualified':
          folder = 'disqualified';
          break;
        default:
          folder = 'triage';
      }

      const relativePath = `${folder}/${r.record_ref}_${safeAcc}.md`;
      outputPaths.push(relativePath);

      if (!files[relativePath]) {
        files[relativePath] = generateConversationMarkdown(r, route);
      }
    });

    manifestRows.push({
      source_type: r.source_type,
      source_id: r.source_id,
      record_ref: r.record_ref,
      applied_revision: r.applied_revision,
      routes: r.assignedRoutes,
      output_paths: outputPaths,
      processing_state: r.processingState,
      is_manual_override: r.isManualOverride,
      analysis_freshness: r.analysisFreshness,
      evidence_citations_count: r.analysis?.supportingCitations?.length || 0,
      derived_account: r.derivedAccount,
      person: r.personName,
      person_role: r.personRole,
    });
  });

  // Daily Manager Brief for 21 August 2026 (Asia/Kolkata)
  const dailyBriefPath = 'daily_brief/manager_brief_2026_08_21.md';
  files[dailyBriefPath] = generateDailyBriefMarkdown(records);

  // Machine-readable Manifest JSON
  const manifestJson = JSON.stringify(
    {
      export_version: '2.0.0',
      exported_at: new Date().toISOString(),
      dataset_scope: '21 August 2026 (Asia/Kolkata)',
      total_records: records.length,
      records_with_usable_text: records.filter(r => r.hasUsableText).length,
      total_active_output_files: Object.keys(files).length,
      manifest: manifestRows,
    },
    null,
    2
  );
  files['manifest.json'] = manifestJson;

  // Machine-readable Manifest CSV
  let csv = 'source_type,source_id,record_ref,applied_revision,routes,output_paths,processing_state,is_manual_override,analysis_freshness,evidence_citations_count,person,person_role,derived_account\n';
  manifestRows.forEach(row => {
    const routesStr = `"${row.routes.join('; ')}"`;
    const pathsStr = `"${row.output_paths.join('; ')}"`;
    const accStr = `"${(row.derived_account || '').replace(/"/g, '""')}"`;
    const personStr = `"${row.person.replace(/"/g, '""')}"`;
    csv += `${row.source_type},${row.source_id},${row.record_ref},${row.applied_revision},${routesStr},${pathsStr},${row.processing_state},${row.is_manual_override},${row.analysis_freshness},${row.evidence_citations_count},${personStr},${row.person_role},${accStr}\n`;
  });
  files['manifest.csv'] = csv;

  return { files, manifestRows, manifestJson, manifestCsv: csv };
}

// Download complete zip bundle
export async function downloadExportZip(records: EnrichedRecord[]): Promise<void> {
  const { files } = buildExportBundle(records);
  const zip = new JSZip();

  Object.entries(files).forEach(([relPath, content]) => {
    zip.file(relPath, content);
  });

  const blob = await zip.generateAsync({ type: 'blob' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `spendnest_revenue_inbox_export_${new Date().toISOString().slice(0, 10)}.zip`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
